# Things that stand in the world: plants, the torch, the first crafting stations and the chest.
# Each is drawn inside the block with room for the dark line the tool puts round it.

def obj(name, text, pal, K=0x1C1820, line=True):
    g = part(text, pal)
    if g.w != 16 or g.h != 16:
        raise ValueError("%s must be 16x16" % name)
    if line:
        add_outline(g, K)
    TILES[name] = g

